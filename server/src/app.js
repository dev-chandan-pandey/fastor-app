import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { env } from './config/env.js';
import authRoutes from './routes/authRoutes.js';
import productRoutes from './routes/productRoutes.js';
import orderRoutes from './routes/orderRoutes.js';
import profileRoutes from './routes/profileRoutes.js';
import { notFound, errorHandler } from './middleware/errorHandler.js';
const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: env.clientOrigin.split(',').map(x => x.trim()), credentials: false }));
app.use(express.json({ limit: '32kb' }));
app.use('/api/auth/otp', rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: 'draft-7', legacyHeaders: false, message: { success: false, error: { message: 'Too many verification requests. Try again later.' } } }));
app.get('/api/health', (_req, res) => res.json({ success: true, data: { status: 'ok', service: 'fastor-api', timestamp: new Date().toISOString() } }));
app.use('/api/auth', authRoutes);
app.use('/api/products', productRoutes);
app.use('/api/orders', orderRoutes);
app.use('/api/profile', profileRoutes);
app.use(notFound); app.use(errorHandler);
export default app;
